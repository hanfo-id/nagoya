/* Generate the offline browser payload from the authoritative itinerary. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const dir = path.resolve(__dirname, '../data');
const {destination,days,timezone,booking_links:bookingLinks} = JSON.parse(fs.readFileSync(
  path.join(dir,'nagoya_2026-12-10_14.json'),'utf8'));
const places = new Map();
const dates = Array.from({length: 5}, (_, i) => `2026-12-${10 + i}`);
const counts = [6,29,23,17,8];
assert.equal(timezone, 'Asia/Tokyo');
assert.deepEqual(days.map(day => day.date), dates);
assert.deepEqual(days.map(day => day.events.length), counts);
const ids = new Set();
for (const day of days) {
  const contiguous = dates.slice(1,3).includes(day.date);
  let end = '';
  for (const event of day.events) {
    assert.match(event.id, /^[\w-]+$/);
    assert.ok(!ids.has(event.id), event.id);
    assert.match(event.start, /^([01]\d|2[0-3]):[0-5]\d$/);
    assert.ok(event.start >= end && (!event.end || event.end >= event.start), event.id);
    if (end && contiguous) assert.equal(event.start,end,event.id+' must follow the previous block');
    if (event.end) assert.match(event.end, /^([01]\d|2[0-3]):[0-5]\d$/);
    assert.ok(event.description.trim() && event.details.length >= 2 && event.details.every(s => s.trim()), event.id);
    const {id,name,japaneseName,address,mapUrl} = event.place;
    assert.match(id, /^[a-z][A-Za-z0-9]*(?:-[a-z0-9]+)*$/);
    assert.ok(name?.trim() && japaneseName?.trim() && address?.trim(), event.id);
    const map = new URL(mapUrl);
    assert.equal(map.origin+map.pathname, 'https://www.google.com/maps/search/', event.id);
    assert.equal(map.searchParams.get('query'), japaneseName+' '+address, event.id);
    if (places.has(id)) assert.deepEqual(places.get(id), event.place, event.id);
    else places.set(id,event.place);
    ids.add(event.id);
    end = event.end || event.start;
  }
}
const payload = {destination, timezone, days, bookingLinks};
fs.writeFileSync(path.join(dir, 'itinerary.js'), '/* Generated by scripts/build-itinerary.cjs. */\nconst ITINERARY_SOURCE = ' + JSON.stringify(payload) + ';\n', 'utf8');
console.log('Validated 83 events across five days, venue links and time blocks.');
