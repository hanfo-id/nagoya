const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {loadItinerary}=require('../scripts/load-itinerary.cjs');

const context=loadItinerary();
const run=code=>vm.runInContext(code,context);
const snapshot=code=>JSON.parse(run('JSON.stringify('+code+')'));
run("const esc=s=>String(s);");
vm.runInContext(fs.readFileSync('numbered-map.js','utf8'),context);
for(let i=0;i<5;i++){
 const pins=snapshot('getMapStops(state,'+i+')');
 pins.forEach((pin,index)=>{
  assert.equal(pin.number,index+1);
  assert.ok(pin.location.lat>34&&pin.location.lat<36,pin.eventId);
  assert.ok(pin.location.lng>136&&pin.location.lng<138,pin.eventId);
  assert.match(pin.location.source,/^https:\/\//);
  assert.ok(pin.address&&pin.jp&&pin.query,pin.eventId);
  if(pin.location.kind==='area-anchor')assert.ok(pin.location.note,pin.id);
 });
}
assert.equal(run('EVENTS_BY_ID.get("b07").placeId'),'nagashima');
assert.equal(run('REGION_IDS.city.has("nagashima")'),false);
assert.equal(run('Object.hasOwn(REGION_IDS,"gero")'),false);
assert.equal(run('REGION_IDS.nabana.has("beerGarden")'),true);
assert.ok(run('MAP_LOCATIONS.nabana.lng<MAP_LOCATIONS.jrNagoya.lng'));
const same=run('const friday=getMapStops(state,1);popupContent(friday.find(p=>p.eventId==="f17"),friday)');
assert.match(same,/같은 위치의 일정/);
for(const id of ['f16','f17','f18','f19','f20','f-chiikawa','s20'])assert.ok(same.includes('data-place-detail="'+id+'"'));
assert.ok(run('MAP_LOCATIONS.animateParco.lng>MAP_LOCATIONS.mugiwara.lng'));
assert.ok(run('MAP_LOCATIONS.heroPopup.lat<MAP_LOCATIONS.mugiwara.lat'));
assert.ok(run('MAP_LOCATIONS.flightOfDreams.lat<MAP_LOCATIONS.airport.lat'));
assert.equal(run('MAP_LOCATIONS.bape.source'),'https://jp.bape.com/pages/store-list/nagoya');
assert.equal(run('MAP_LOCATIONS.hoods.source'),'https://www.doubledutch-jp.com/hoods-nagoya');
const saturday=snapshot('getMapStops(state,2)');
assert.equal(saturday.length,24);
const dessert=saturday.find(p=>p.eventId==='s-kurin');
assert.equal(dessert.address,'愛知県名古屋市中区大須3-37-40');
assert.match(dessert.query,/和栗モンブラン専門店 栗りん/);
assert.deepEqual(dessert.location,saturday.find(p=>p.eventId==='s-kurin-transfer').location);
assert.equal(saturday.find(p=>p.eventId==='s-donki').address,'愛知県名古屋市中区錦3-17-15');
assert.equal(saturday.at(-1).eventId,'s-hotel-return');
assert.equal(saturday.find(p=>p.eventId==='d5-keshiki').location.kind,'address');
const monday=snapshot('getMapStops(state,4)');
assert.equal(monday.length,9);
assert.equal(monday.find(p=>p.eventId==='d5-kato').address,'愛知県名古屋市東区東桜1-3-2 さくらビル1F');
assert.equal(monday.find(p=>p.eventId==='d5-flight-park').id,'flightOfDreams');
assert.ok(monday.every(p=>p.id!=='keshiki'));
assert.equal(saturday.find(p=>p.eventId==='s08').address,'名古屋市中区大須2-18-41');
assert.equal(saturday.find(p=>p.eventId==='s-osu-walk').location.kind,'area-anchor');
assert.ok(saturday.every(p=>!['animateParco','mugiwara','heroPopup','sunroad','coffeeBuriko','sushi'].includes(p.id)));
assert.equal(saturday.find(p=>p.eventId==='s-shinsuzume').location.kind,'address');
assert.deepEqual(saturday.find(p=>p.eventId==='s-okoge').location,saturday.find(p=>p.eventId==='s-sakae-transfer').location);
assert.match(saturday.find(p=>p.eventId==='s-okoge').query,/月島もんじゃ おこげ 栄.*3-9-29/);
assert.ok(run('MAP_LOCATIONS.unayasu.lng>MAP_LOCATIONS.jrNagoya.lng'));
const map=fs.readFileSync('numbered-map.js','utf8');
assert.doesNotMatch(map,/setLatLng|layerPointToLatLng|polyline/);
console.log('PASS: all five days of event pins, sourced coordinates, region zoom subsets and same-coordinate selection without marker displacement.');
